#!/usr/bin/env bash
# Build dist/<skill>.md: one self-contained file per skill (SKILL.md + references +
# script index) for chat models that can't read folders. Paste it into a ChatGPT
# project, a Gemini Gem, a Claude project, or any system prompt.
# Run after every edit to skills/.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")" && pwd)
mkdir -p "$ROOT/dist"
for skill in "$ROOT"/skills/*/; do
    skill=${skill%/}
    [ -f "$skill/SKILL.md" ] || continue
    name=$(basename "$skill")
    out="$ROOT/dist/$name.md"
    {
        echo "<!-- generated by bundle.sh from skills/$name; edit the sources, not this file -->"
        cat "$skill/SKILL.md"
        if [ -d "$skill/references" ]; then
            for ref in "$skill"/references/*.md; do
                [ -f "$ref" ] || continue
                printf '\n\n---\n\n<!-- references/%s -->\n\n' "$(basename "$ref")"
                cat "$ref"
            done
        fi
        if [ -d "$skill/scripts" ]; then
            printf '\n\n---\n\n## Scripts in the repo (skills/%s/scripts)\n\n' "$name"
            echo "Not runnable from a chat; on a machine with the repo, run them as described above."
            echo
            for s in "$skill"/scripts/*; do
                [ -f "$s" ] || continue
                desc=$(sed -n '2,3p' "$s" | sed -e 's/^#\s*//' -e 's/^"""//' | head -1)
                echo "- \`$(basename "$s")\`: $desc"
            done
        fi
    } > "$out"
    echo "wrote dist/$name.md ($(wc -c < "$out") bytes)"
done
